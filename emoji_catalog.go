package groupme

import "strconv"

// CustomEmoji is one named choice captured from GroupMe's native reaction
// picker. Pack identity is independent of Unicode reaction codes.
type CustomEmoji struct {
	PackID    string `json:"pack_id"`
	PackIndex string `json:"pack_index"`
	Title     string `json:"title"`
}

// CustomEmojiPack describes the exact contiguous picker range observed for a
// known pack. It does not claim these are all packs the provider may ever add.
type CustomEmojiPack struct {
	PackID   string `json:"pack_id"`
	MinIndex int    `json:"min_index"`
	MaxIndex int    `json:"max_index"`
	Count    int    `json:"count"`
}

// CustomEmojiCatalog returns an independent copy of all 549 native picker
// choices observed on 2026-10-23, in native pack/index order. No network is used.
func CustomEmojiCatalog() []CustomEmoji {
	result := make([]CustomEmoji, 0, 549)
	for _, pack := range nativeCustomEmojiPacks {
		for index, title := range pack.titles {
			result = append(result, CustomEmoji{PackID: pack.id, PackIndex: strconv.Itoa(index), Title: title})
		}
	}
	return result
}

// CustomEmojiPacks returns independent value copies of the verified ranges.
func CustomEmojiPacks() []CustomEmojiPack {
	result := make([]CustomEmojiPack, 0, len(nativeCustomEmojiPacks))
	for _, pack := range nativeCustomEmojiPacks {
		result = append(result, CustomEmojiPack{PackID: pack.id, MinIndex: 0, MaxIndex: len(pack.titles) - 1, Count: len(pack.titles)})
	}
	return result
}

